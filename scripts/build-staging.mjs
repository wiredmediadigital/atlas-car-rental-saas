import { spawnSync } from 'node:child_process'
import { writeFileSync, rmSync } from 'node:fs'
import { resolve } from 'node:path'

import {
  STAGING_BUILD_INTENT,
  STAGING_PROJECT,
  validateStagingEnvironment,
  verifyStagingArtifact,
} from './staging-build-guard.mjs'

const root = resolve(import.meta.dirname, '..')
const output = resolve(root, 'dist-staging')
const env = { ...process.env, PEVVY_STAGING_BUILD_INTENT: STAGING_BUILD_INTENT }
const errors = validateStagingEnvironment(env)
if (errors.length > 0) {
  console.error(`Staging build blocked: ${errors.join(', ')}`)
  process.exit(1)
}

function run(relativeScript, args) {
  const result = spawnSync(process.execPath, [resolve(root, relativeScript), ...args], {
    cwd: root,
    env,
    stdio: 'inherit',
  })
  if (result.status !== 0) throw new Error('Staging build command failed')
}

let buildStarted = false
try {
  run('node_modules/typescript/bin/tsc', ['-b'])
  buildStarted = true
  run('node_modules/vite/bin/vite.js', ['build', '--mode', 'staging'])
  const result = verifyStagingArtifact(output, env.VITE_SUPABASE_PUBLISHABLE_KEY)
  if (result.errors.length > 0)
    throw new Error(`Staging artifact rejected: ${result.errors.join(', ')}`)
  writeFileSync(
    resolve(output, 'staging-build-manifest.json'),
    JSON.stringify(
      {
        buildMode: 'staging',
        projectRef: STAGING_PROJECT,
        contentSha256: result.contentSha256,
        fileCount: result.fileCount,
      },
      null,
      2,
    ) + '\n',
  )
  console.log(
    `Staging artifact verified: ${result.fileCount} files; SHA-256 ${result.contentSha256}`,
  )
} catch (error) {
  // This fixed path contains only artifacts generated by the staging build.
  if (buildStarted && output === resolve(root, 'dist-staging'))
    rmSync(output, { recursive: true, force: true })
  console.error(error instanceof Error ? error.message : 'Staging build failed')
  process.exitCode = 1
}
